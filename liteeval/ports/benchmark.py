"""Narrow contracts used by benchmark application services."""
from typing import Protocol
from liteeval.domain.benchmark import Package


class PackageLoader(Protocol):
    def load(self, path) -> Package: ...


class ResourceStore(Protocol):
    def put(self, data: bytes) -> str: ...
    def get(self, digest: str) -> bytes: ...


class BenchmarkRepository(Protocol):
    def publish(self, project_id, package, content) -> dict: ...
    def release(self, project_id, release_id) -> dict: ...
    def start(self, project_id, plan) -> str: ...
    def finish(self, run_id, result) -> None: ...
    def event(self, run_id, kind, payload) -> None: ...


class AgentHarness(Protocol):
    async def run(self, public_task: dict, context) -> dict: ...


class DialogueHarness(Protocol):
    def prepare(self, runtime, spec: dict) -> list[str]: ...
    async def send_turn(self, runtime, command: list[str], spec: dict, request: dict, timeout: float, emit) -> dict: ...


class EvaluationHarness(Protocol):
    async def evaluate(self, task, submission, context) -> list[dict]: ...
